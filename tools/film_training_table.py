# Writes crates/film/src/training_table.rs: the 190 measured surface reflectances of rawtoaces-data's training set,
# 380..780 nm every 5 nm, which lightcraft-film fits each stock's lab-scanner colour matrix to.
#
#   git clone https://github.com/AcademySoftwareFoundation/rawtoaces-data ../rawtoaces-data
#   git -C ../rawtoaces-data checkout v1.1.0
#   python3 tools/film_training_table.py ../rawtoaces-data crates/film/src/training_table.rs
#
# The reflectances are rawtoaces-data's `data/training/training_spectral.json` (Academy Software Foundation,
# Apache-2.0), copied as measured (rounded to 5 significant digits).
import json
import subprocess
import sys

WL = range(380, 781, 5)


def num(v):
    s = f"{v:.5g}"
    return s if any(c in s for c in ".e") else s + ".0"


def main():
    root, out = sys.argv[1], sys.argv[2]
    commit = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    with open(f"{root}/data/training/training_spectral.json") as f:
        main_data = json.load(f)["spectral_data"]["data"]["main"]
    patches = len(main_data["380"])
    rows = []
    for p in range(patches):
        rows.append("    [" + ", ".join(num(main_data[str(w)][p]) for w in WL) + "],")
    text = (
        "// Generated by tools/film_training_table.py. Do not edit by hand.\n"
        "// Measured surface reflectances, rawtoaces-data `data/training/training_spectral.json`\n"
        f"// (https://github.com/AcademySoftwareFoundation/rawtoaces-data, commit {commit}), Academy Software\n"
        "// Foundation, Apache-2.0 (LICENSE-APACHE). See NOTICE and assets/ATTRIBUTION.md.\n"
        "use crate::spectrum::Spectrum;\n\n"
        f"/// {patches} measured surface reflectances (380–780 nm every 5 nm). Measured values, not approximated constants.\n"
        "#[rustfmt::skip]\n"
        "#[allow(clippy::approx_constant)]\n"
        f"pub(crate) static REFLECTANCES: [Spectrum; {patches}] = [\n" + "\n".join(rows) + "\n];\n"
    )
    with open(out, "w") as f:
        f.write(text)


main()
